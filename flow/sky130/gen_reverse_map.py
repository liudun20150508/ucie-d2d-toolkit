#!/usr/bin/env python3
"""Auto-generate yosys reverse-techmap models for ALL sky130 cells from PDK JSONs.
Combinational cells -> $lut truth table; latches -> $_DLATCH_*; flops skipped
(hand-written models in reverse_map.v cover dfxtp/edfxtp with correct semantics).
"""
import glob, json, os, re

CELLS_DIR = "../../resources/sky130/cells"  # 需自备 skywater-pdk cell JSON（*.lib.json，未随包分发）
CORNER = "tt_025C_1v80"
OUT = "scripts/reverse_map_auto.v"

def parse_fn(expr, inputs):
    """Evaluate a liberty function expression over inputs dict (name->0/1)."""
    e = expr.replace("&&", " and ").replace("||", " or ")
    e = e.replace("!", " not ").replace("~", " not ")
    e = e.replace("&", " and ").replace("|", " or ").replace("^", " xor ")
    # tokenize identifiers, keep ternary
    e = re.sub(r"(\b[A-Za-z_][A-Za-z0-9_]*\b)(?![(])",
               lambda m: str(inputs.get(m.group(1), m.group(1))), e)
    # python truthiness for ternary
    e = e.replace("?", " if ").replace(":", " else ")
    try:
        return 1 if eval(e, {"__builtins__": {}}, {}) else 0
    except Exception:
        return None

def gen_lut(expr, pins, out_pin):
    """Generate $lut truth table lines for expr."""
    in_pins = [p for p in pins if p != out_pin]
    in_pins.sort(key=lambda p: (expr.find(p) if p in expr else 99, p))
    n = len(in_pins)
    if n > 16:  # beyond $lut limits
        return None
    table = 0
    for val in range(1 << n):
        d = {}
        for i, p in enumerate(in_pins):
            d[p] = (val >> i) & 1
        r = parse_fn(expr, d)
        if r is None:
            return None
        table |= (r << val)
    return in_pins, n, table

out = ["// AUTO-GENERATED by gen_reverse_map.py — $lut models for sky130 cells",
       "// (LEC gate-side models; flops/latches covered by hand-written models)"]
count = 0
for jf in sorted(glob.glob(f"{CELLS_DIR}/*/*__{CORNER}.lib.json")):
    with open(jf) as f:
        c = json.load(f)
    cname = os.path.basename(jf).replace(f"__{CORNER}.lib.json", "")
    pins = {}
    for pk, pv in c.items():
        if pk.startswith("pin,"):
            pins[pk.split(",", 1)[1]] = pv
    # skip flops/latches (hand-written)
    if any(k.startswith("ff,") or k.startswith("lat,") for k in c):
        continue
    outputs = [(pn, pv) for pn, pv in pins.items()
               if pv.get("direction") == "output" and "function" in pv]
    if not outputs:
        continue
    # skip tristate / z outputs
    if any("1'bz" in pv["function"] or "z" in pv["function"].lower() for _, pv in outputs):
        continue
    all_in = [pn for pn, pv in pins.items() if pv.get("direction") == "input"]
    body = []
    ok = True
    inst = 0
    for opn, opv in outputs:
        r = gen_lut(opv["function"], [opn] + all_in, opn)
        if r is None:
            ok = False
            break
        in_pins, n, table = r
        if n == 0:
            body.append(f"  assign {opn} = 1'b{table};")
        else:
            body.append(f"  $lut #(.WIDTH({n}), .LUT({(1 << n)}'h{table:x})) _TECHMAP_REPLACE_{inst} "
                        f"(.A({{{', '.join(in_pins)}}}), .Y({opn}));")
        inst += 1
    if not ok:
        continue
    portlist = ", ".join(all_in + [opn for opn, _ in outputs])
    out.append(f"module {cname} ({portlist});")
    for p in all_in:
        out.append(f"  input {p};")
    for opn, _ in outputs:
        out.append(f"  output {opn};")
    out.extend(body)
    out.append("endmodule")
    count += 1

with open(OUT, "w") as f:
    f.write("\n".join(out) + "\n")
print(f"generated {count} combinational cell models -> {OUT}")
