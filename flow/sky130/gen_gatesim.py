#!/usr/bin/env python3
"""Auto-generate functional Verilog models for ALL sky130 combinational cells."""
import glob, json, os

CELLS_DIR = "../../resources/sky130/cells"  # 需自备 skywater-pdk cell JSON（*.lib.json，未随包分发）
CORNER = "tt_025C_1v80"
SKIP = {"sky130_fd_sc_hd__and2_1","sky130_fd_sc_hd__or2_1","sky130_fd_sc_hd__xor2_1",
        "sky130_fd_sc_hd__xnor2_1","sky130_fd_sc_hd__nand2_1","sky130_fd_sc_hd__nor2_1",
        "sky130_fd_sc_hd__and2b_1","sky130_fd_sc_hd__or2b_1","sky130_fd_sc_hd__inv_1",
        "sky130_fd_sc_hd__buf_1","sky130_fd_sc_hd__mux2_1","sky130_fd_sc_hd__clkbuf_1",
        "sky130_fd_sc_hd__clkbuf_2","sky130_fd_sc_hd__clkbuf_4","sky130_fd_sc_hd__clkbuf_8",
        "sky130_fd_sc_hd__clkbuf_16","sky130_fd_sc_hd__lpflow_clkbufkapwr_1",
        "sky130_fd_sc_hd__lpflow_clkbufkapwr_2","sky130_fd_sc_hd__lpflow_clkbufkapwr_4",
        "sky130_fd_sc_hd__lpflow_clkbufkapwr_8","sky130_fd_sc_hd__lpflow_clkbufkapwr_16"}

OUT = "scripts/sky130_gatesim_auto.v"

out = ["// AUTO-GENERATED by gen_gatesim.py — functional models for sky130 cells"]
count = 0
for jf in sorted(glob.glob(f"{CELLS_DIR}/*/*__{CORNER}.lib.json")):
    with open(jf) as f:
        c = json.load(f)
    cname = os.path.basename(jf).replace(f"__{CORNER}.lib.json", "")
    if cname in SKIP:
        continue
    if any(k.startswith("ff,") or k.startswith("lat,") for k in c):
        continue
    pins = {}
    for pk, pv in c.items():
        if pk.startswith("pin,"):
            pins[pk.split(",", 1)[1]] = pv
    outputs = [(pn, pv) for pn, pv in pins.items()
               if pv.get("direction") == "output" and "function" in pv]
    if not outputs:
        continue
    if any("1'bz" in pv["function"] or "z" in pv["function"].lower() for _, pv in outputs):
        continue
    all_in = [pn for pn, pv in pins.items() if pv.get("direction") == "input"]
    # skip cells whose functions reference internal nodes (IQ/IQ_N etc.)
    import re as _re
    bad = False
    for opn, opv in outputs:
        for ident in _re.findall(r"[A-Za-z_][A-Za-z0-9_]*", opv["function"]):
            if ident not in pins and ident not in ("1'b0", "1'b1", "0", "1"):
                bad = True
    if bad:
        continue
    portlist = ", ".join(all_in + [opn for opn, _ in outputs])
    out.append(f"module {cname} ({portlist});")
    for p in all_in:
        out.append(f"  input {p};")
    for opn, _ in outputs:
        out.append(f"  output {opn};")
    for opn, opv in outputs:
        fn = opv["function"]
        out.append(f"  assign {opn} = {fn};")
    out.append("endmodule")
    count += 1

with open(OUT, "w") as f:
    f.write("\n".join(out) + "\n")
print(f"generated {count} combinational models -> {OUT}")
